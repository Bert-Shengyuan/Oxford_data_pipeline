# ══════════════════════════════════════════════════════════════════════════════
# §2  VISUALISE NEURAL VECTOR FIELDS IN LATENT SPACE
#
# The DSA package works on data of shape (trials, time, channels) or
# (time, channels).  We add a singleton trial dimension: (1, T, N).
#
# To inspect the *neural vector field* we:
#   (a) Reduce to 2-D via PCA for visualisation.
#   (b) At each sampled latent state z_t, plot the flow  Δz = z_{t+1} - z_t
#       as an arrow.  This is the empirical vector field in latent space.
# ══════════════════════════════════════════════════════════════════════════════

from sklearn.decomposition import PCA

def get_pca_trajectory(X: np.ndarray, n_components: int = 2):
    """Project (T, N) activity into top principal components."""
    pca = PCA(n_components=n_components)
    return pca.fit_transform(X), pca          # (T, 2)


def plot_vector_field(ax, Z: np.ndarray, title: str, color: str,
                      subsample: int = 8):
    """
    Plot empirical vector field from latent trajectory Z ∈ ℝ^{T×2}.

    At each sampled time point t, the arrow represents:
        Δz(t) = z(t+1) − z(t)        (discrete-time flow)

    This is the observed neural vector field before any Koopman fitting.
    """
    T_ = len(Z)
    t_idx = np.arange(0, T_ - 1, subsample)

    # Background: coloured trajectory
    ax.scatter(Z[:, 0], Z[:, 1], c=np.arange(T_),
               cmap='plasma', s=4, alpha=0.6, linewidths=0)

    # Foreground: flow arrows
    dZ = np.diff(Z, axis=0)                          # (T-1, 2)
    ax.quiver(Z[t_idx, 0], Z[t_idx, 1],
              dZ[t_idx, 0], dZ[t_idx, 1],
              color=color, alpha=0.8, scale=None,
              scale_units='xy', angles='xy',
              width=0.004, headwidth=4)

    ax.set_title(title, fontsize=10, color=color, fontweight='bold')
    ax.set_xlabel(r'$\mathrm{PC}_1$', fontsize=9)
    ax.set_ylabel(r'$\mathrm{PC}_2$', fontsize=9)
    ax.set_aspect('equal')


Z_A,  _  = get_pca_trajectory(pop_A)
Z_Bc, _  = get_pca_trajectory(pop_Bc)
Z_Bd, _  = get_pca_trajectory(pop_Bd)

fig, axes = plt.subplots(1, 3, figsize=(15, 4))
plot_vector_field(axes[0], Z_A,  'Pop A  (ring)', '#2166ac')
plot_vector_field(axes[1], Z_Bc, r'Pop $B_c$  (conjugate ring)', '#4dac26')
plot_vector_field(axes[2], Z_Bd, r'Pop $B_d$  (fixed point)', '#d01c8b')
fig.suptitle(r'Neural Vector Fields in PC Space'
             '\n'
             r'Arrows: $\Delta \mathbf{z}(t) = \mathbf{z}(t+1) - \mathbf{z}(t)$',
             fontsize=12)
plt.tight_layout()
plt.savefig('neural_vector_fields.png', dpi=150, bbox_inches='tight')



