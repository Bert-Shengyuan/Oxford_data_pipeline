"""
DSA Pedagogical Example — using the official dsa-metric package.
pip install dsa-metric

Two neural populations (N=10 neurons each):
  Pop A   : ring attractor  (limit cycle, S¹ topology)
  Pop B_c : ring attractor, different random readout W  (conjugate to A)
  Pop B_d : stable fixed point  (different topology from A)
"""

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec

# ─── official package imports ────────────────────────────────────────────────
from DSA import DSA
from DSA.dmd import DMD
from DSA.simdist import SimilarityTransformDist


# ══════════════════════════════════════════════════════════════════════════════
# §1  SIMULATE NEURAL POPULATIONS
#
# Each population is generated by projecting a low-dimensional latent
# trajectory through a random readout matrix W ∈ ℝ^{2 × N}.
#
#   r(t) = W x(t) + ε,    ε ~ N(0, σ²)
#
# Two populations with DIFFERENT W but the SAME latent x(t) are
# *conjugate*: same dynamics, different geometry.
# ══════════════════════════════════════════════════════════════════════════════

def simulate_ring(N: int = 10, T: int = 600, noise: float = 0.04, seed: int = 0):
    """
    Limit-cycle (ring) attractor.
    Latent:  x(t) = [sin(t),  cos(t)]   → closed orbit on S¹.
    Shape returned: (T, N)
    """
    rng = np.random.default_rng(seed)
    t   = np.linspace(0, 6 * np.pi, T)          # ~3 full cycles
    lat = np.column_stack([np.sin(t), np.cos(t)])  # (T, 2)
    W   = rng.standard_normal((2, N))
    return lat @ W + noise * rng.standard_normal((T, N))


def simulate_fixed_point(N: int = 10, T: int = 600, noise: float = 0.04, seed: int = 0):
    """
    Stable fixed-point attractor.
    Latent:  x(t) = e^{-t/3} [sin(4t), cos(4t)]  → spiral converging to origin.
    Topology is fundamentally different from the ring (S¹ vs ℝ⁰).
    Shape returned: (T, N)
    """
    rng = np.random.default_rng(seed)
    t   = np.linspace(0, 12, T)
    lat = np.column_stack([np.exp(-t / 3) * np.sin(4 * t),
                            np.exp(-t / 3) * np.cos(4 * t)])
    W   = rng.standard_normal((2, N))
    return lat @ W + noise * rng.standard_normal((T, N))


np.random.seed(42)
N_NEURONS = 10
T         = 600

pop_A  = simulate_ring(N_NEURONS, T, seed=1)   # (T, N)
pop_Bc = simulate_ring(N_NEURONS, T, seed=3)   # conjugate ring
pop_Bd = simulate_fixed_point(N_NEURONS, T, seed=3)

